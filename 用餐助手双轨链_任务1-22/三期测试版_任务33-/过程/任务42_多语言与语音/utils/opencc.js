// 词级映射按 key 长度降序（长词优先匹配）
const PHRASE_KEYS = Object.keys(PHRASE_MAP).sort((a, b) => b.length - a.length)

// 简转繁主函数
function toTraditional(text) {
  if (!text) return ''
  let s = String(text)

  // 1) 词级替换（长词优先）
  PHRASE_KEYS.forEach((k) => {
    if (s.indexOf(k) >= 0) {
      s = s.split(k).join(PHRASE_MAP[k])
    }
  })

  // 2) 字级兜底（逐字转换）
  const out = []
  for (let i = 0; i < s.length; i++) {
    const ch = s[i]
    out.push(CHAR_MAP[ch] || ch)
  }
  return out.join('')
}

